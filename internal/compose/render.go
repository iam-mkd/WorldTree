package compose

import (
	"bytes"
	"fmt"
	"strconv"

	"go.yaml.in/yaml/v3"
)

// Header is the first line of every generated override.
const Header = "# Generated by worldtree. Do not edit: it is rewritten on every `worldtree up`.\n"

// Render returns the override YAML for the plan. leases maps every PortRequest.Key
// to the host port leased for it; a missing lease is an error, never a silent default.
//
// The override uses compose merge tags (Compose >= 2.24):
//   - container_name: !reset null   drops fixed names
//   - ports: !override [...]        replaces the list instead of appending to it
//
// Bind mounts merge with the original by target, so only re-pointed binds are listed.
func (p *Plan) Render(leases map[string]int) ([]byte, error) {
	for _, r := range p.Ports {
		if _, ok := leases[r.Key]; !ok {
			return nil, fmt.Errorf("render: no port leased for %s", r.Key)
		}
	}
	root := mapping()
	add(root, "name", str(p.opts.Project))

	services := mapping()
	for _, name := range sortedKeys(p.services) {
		sp := p.services[name]
		s := mapping()
		if sp.resetContainerName {
			add(s, "container_name", &yaml.Node{Kind: yaml.ScalarNode, Tag: "!reset", Value: "null"})
		}
		add(s, "labels", p.labels())
		if sp.ports != nil {
			seq := &yaml.Node{Kind: yaml.SequenceNode, Tag: "!override"}
			for _, e := range sp.ports {
				seq.Content = append(seq.Content, portNode(e, leases))
			}
			add(s, "ports", seq)
		}
		if len(sp.binds) > 0 {
			seq := &yaml.Node{Kind: yaml.SequenceNode}
			for _, b := range sp.binds {
				m := mapping()
				add(m, "type", str("bind"))
				add(m, "source", str(b.Source))
				add(m, "target", str(b.Target))
				bind := mapping()
				add(bind, "create_host_path", &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!bool", Value: "true"})
				add(m, "bind", bind)
				seq.Content = append(seq.Content, m)
			}
			add(s, "volumes", seq)
		}
		add(services, name, s)
	}
	add(root, "services", services)

	for _, kind := range []struct {
		key string
		res map[string]resource
	}{{"networks", p.networks}, {"volumes", p.volumes}} {
		if len(kind.res) == 0 {
			continue
		}
		top := mapping()
		for _, key := range sortedKeys(kind.res) {
			r := mapping()
			if n := kind.res[key].rename; n != "" {
				add(r, "name", str(n))
			}
			add(r, "labels", p.labels())
			add(top, key, r)
		}
		add(root, kind.key, top)
	}

	var buf bytes.Buffer
	buf.WriteString(Header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(&yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{root}}); err != nil {
		return nil, fmt.Errorf("render: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("render: %w", err)
	}
	return buf.Bytes(), nil
}

func portNode(e portEntry, leases map[string]int) *yaml.Node {
	m := mapping()
	add(m, "target", &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!int", Value: strconv.FormatUint(uint64(e.port.Target), 10)})
	if e.key != "" {
		add(m, "published", str(strconv.Itoa(leases[e.key])))
	}
	if e.port.HostIP != "" {
		add(m, "host_ip", str(e.port.HostIP))
	}
	if e.port.Protocol != "" {
		add(m, "protocol", str(e.port.Protocol))
	}
	if e.port.Mode != "" && e.port.Mode != "ingress" {
		add(m, "mode", str(e.port.Mode))
	}
	if e.port.Name != "" {
		add(m, "name", str(e.port.Name))
	}
	if e.port.AppProto != "" {
		add(m, "app_protocol", str(e.port.AppProto))
	}
	return m
}

func (p *Plan) labels() *yaml.Node {
	m := mapping()
	add(m, LabelWorld, str(p.opts.WorldID))
	return m
}

func mapping() *yaml.Node { return &yaml.Node{Kind: yaml.MappingNode} }

// str is a plain string scalar; the encoder quotes it when needed ("8080", "::1", "null").
func str(v string) *yaml.Node { return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: v} }

func add(m *yaml.Node, key string, v *yaml.Node) {
	m.Content = append(m.Content, str(key), v)
}

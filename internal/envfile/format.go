package envfile

import (
	"bufio"
	"bytes"
	"fmt"
	"strings"

	"github.com/compose-spec/compose-go/v2/dotenv"
)

// Header is the first line of the generated env file.
const Header = "# Generated by worldtree for this world. Do not edit: rewritten on every `worldtree up`.\n"

// Formats accepted by Format.
const (
	Dotenv     = "dotenv"
	Sh         = "sh"
	PowerShell = "powershell"
)

// Render returns vars as a dotenv file that compose-go (and so `docker compose`, direnv-style
// loaders and Spring's optional:file:...[.properties]) reads back to exactly the same values.
func Render(vars []Var) []byte {
	var b bytes.Buffer
	b.WriteString(Header)
	for _, v := range vars {
		fmt.Fprintf(&b, "%s=%s\n", v.Key, dotenvQuote(v.Value))
	}
	return b.Bytes()
}

// Parse reads a file written by Render, keeping its order. Values are not interpolated.
func Parse(data []byte) ([]Var, error) {
	noLookup := func(string) (string, bool) { return "", false }
	var vars []Var
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		m, err := dotenv.UnmarshalWithLookup(line, noLookup)
		if err != nil {
			return nil, err
		}
		for k, v := range m {
			vars = append(vars, Var{k, v})
		}
	}
	return vars, sc.Err()
}

// Format renders vars for a shell: Dotenv (KEY=value), Sh (export KEY='value', for eval)
// or PowerShell ($env:KEY = 'value', for Invoke-Expression).
func Format(vars []Var, format string) (string, error) {
	var b strings.Builder
	for _, v := range vars {
		switch format {
		case Dotenv:
			fmt.Fprintf(&b, "%s=%s\n", v.Key, dotenvQuote(v.Value))
		case Sh:
			fmt.Fprintf(&b, "export %s='%s'\n", v.Key, strings.ReplaceAll(v.Value, "'", `'\''`))
		case PowerShell:
			fmt.Fprintf(&b, "$env:%s = '%s'\n", v.Key, strings.ReplaceAll(v.Value, "'", "''"))
		default:
			return "", fmt.Errorf("unknown format %q (want %s, %s or %s)", format, Dotenv, Sh, PowerShell)
		}
	}
	return b.String(), nil
}

// dotenvQuote single-quotes a plain value (compose does not interpolate inside single
// quotes). A value with a single quote, a backslash (a trailing one would escape the
// closing quote) or a line break is double-quoted with \, ", $ escaped and line breaks
// written as \n / \r, so every assignment stays on one physical line for Parse.
func dotenvQuote(v string) string {
	if !strings.ContainsAny(v, "'\\\n\r") {
		return "'" + v + "'"
	}
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`, "\n", `\n`, "\r", `\r`)
	return `"` + r.Replace(v) + `"`
}

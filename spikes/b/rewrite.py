"""Spike B: generate a per-world compose override for an arbitrary compose project.

usage: python rewrite.py <project_dir> <world> <port_base>
Writes <project_dir>/docker-compose.worldtree.yml and <project_dir>/.worldtree.env,
prints actions and UNSUPPORTED/WARN findings. Original compose file is never modified.
"""
import json, os, subprocess, sys

SYSTEM_BINDS = ("/var/run/docker.sock", "/etc/localtime", "/etc/timezone", "/dev/", "/sys/", "/proc/", "/lib/modules")


def compose_config(d):
    # --profile '*' enables every profile so profiled services are rewritten too.
    out = subprocess.run(["docker", "compose", "--project-directory", d, "--profile", "*",
                          "config", "--format", "json", "--no-interpolate"],
                         capture_output=True, text=True)
    if out.returncode:
        sys.exit("compose config failed:\n" + out.stderr)
    raw = json.loads(out.stdout)
    out = subprocess.run(["docker", "compose", "--project-directory", d, "--profile", "*",
                          "config", "--format", "json"], capture_output=True, text=True)
    return raw, json.loads(out.stdout)


def inside(path, root):
    try:
        return os.path.commonpath([os.path.abspath(path), os.path.abspath(root)]) == os.path.abspath(root)
    except ValueError:  # different drives on Windows
        return False


def main(d, world, base):
    raw, cfg = compose_config(d)
    # spike layout is run/<app>/<world>; the real tool would use the repo name.
    project = f"{os.path.basename(os.path.dirname(os.path.abspath(d)))}-{world}".lower()
    port, lines, notes = base, ["# generated by worldtree spike B; do not edit", "services:"], []
    for name, svc in sorted(cfg.get("services", {}).items()):
        body = []
        if "container_name" in svc:
            body.append("    container_name: !reset null")
            notes.append(f"{name}: drop container_name={svc['container_name']}")
        nm = svc.get("network_mode", "")
        if nm == "host":
            notes.append(f"UNSUPPORTED {name}: network_mode=host shares host ports; cannot isolate")
        if svc.get("ports"):
            mapped = []
            for p in svc["ports"]:
                if not p.get("published"):
                    continue  # container-only port, nothing on host
                if "-" in str(p["published"]):
                    notes.append(f"UNSUPPORTED {name}: port range {p['published']}")
                    continue
                ip = p.get("host_ip")
                mapped.append(f'"{ip + ":" if ip else ""}{port}:{p["target"]}/{p.get("protocol", "tcp")}"')
                notes.append(f"{name}: host port {ip or '*'}:{p['published']} -> {port}")
                port += 1
            body.append(f"    ports: !override [{', '.join(mapped)}]")
        vols = []
        for v in svc.get("volumes", []):
            if v.get("type") != "bind":
                continue
            src = v["source"]
            if any(src.startswith(s) for s in SYSTEM_BINDS):
                notes.append(f"WARN {name}: shared system bind {src} (left as is)")
            elif not inside(src, d):
                new = os.path.join(os.path.abspath(d), ".worldtree", "binds",
                                   name + v["target"].replace("/", "_")).replace("\\", "/")
                vols.append(f'      - "{new}:{v["target"]}"')
                notes.append(f"{name}: bind {src} outside project -> {new}")
        if vols:
            body += ["    volumes:"] + vols
        for net, spec in (svc.get("networks") or {}).items():
            if spec and (spec.get("ipv4_address") or spec.get("ipv6_address")):
                notes.append(f"UNSUPPORTED {name}: static IP on network {net}")
        if body:
            lines += [f"  {name}:"] + body
    for kind in ("volumes", "networks"):
        for n, spec in (cfg.get(kind) or {}).items():
            if spec.get("external"):
                notes.append(f"WARN shared external {kind[:-1]} {spec.get('name', n)} (not isolated)")
            elif kind == "networks" and (spec.get("ipam") or {}).get("config"):
                notes.append(f"UNSUPPORTED network {n}: fixed ipam subnet will overlap")
    for name, svc in raw.get("services", {}).items():
        if "build" in svc:
            notes.append(f"{name}: build context kept relative to project dir")
        if "env_file" in svc:
            notes.append(f"{name}: env_file kept (read from project dir)")
        if "profiles" in svc:
            notes.append(f"{name}: profiles {svc['profiles']} kept")
    if len(lines) == 2:
        lines[-1] = "services: {}"
    open(os.path.join(d, "docker-compose.worldtree.yml"), "w", newline="\n").write("\n".join(lines) + "\n")
    main_file = next(f for f in ("compose.yaml", "compose.yml", "docker-compose.yml", "docker-compose.yaml")
                     if os.path.exists(os.path.join(d, f)))
    open(os.path.join(d, ".worldtree.env"), "w", newline="\n").write(
        f"COMPOSE_PROJECT_NAME={project}\nCOMPOSE_PATH_SEPARATOR=:\n"
        f"COMPOSE_FILE={main_file}:docker-compose.worldtree.yml\n")
    print(f"project={project}")
    print("\n".join(notes))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], int(sys.argv[3]))
